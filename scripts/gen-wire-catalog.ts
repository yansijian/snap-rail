/**
 * Wire-catalog generator: renders `docs/wire-catalog.md` from the domain
 * contracts — the same single-source declarations the runtime serves. The
 * catalog is a build artifact: regenerate (`pnpm run gen:wire-catalog`), do
 * not hand-edit; `pnpm test` fails when the file drifts from the contracts.
 *
 * The platform surface (`host.*`, `rpc.describe`, `window.*`) is the
 * gateway's own hand-written face in `@snap-rail/protocol/methods` and is
 * documented here as a fixed preamble, not generated.
 *
 * @module scripts/gen-wire-catalog
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { z } from 'zod'
import type { DomainContract, MethodRow } from '../packages/base/protocol/src/contract.ts'
import { pluginsContract, updateContract } from '../packages/base/app-boot/src/contract.ts'
import { equipmentContract } from '../packages/equipment/equipment/src/wire.ts'
import { stationContract } from '../packages/base/station-rpc/src/contract.ts'

const root = join(import.meta.dirname, '..')
const catalogPath = join(root, 'docs', 'wire-catalog.md')

/** The zod-backed domain contracts, in stable catalog order. Suite
 * contracts (e.g. production) live inside their suite packages and are
 * documented by those repositories — the app-shipped catalog covers the
 * contracts that ride the app. */
const CONTRACTS: readonly DomainContract[] = [
  stationContract,
  pluginsContract,
  updateContract,
  equipmentContract,
]

/** Best-effort JSON Schema; schemas without a JSON shape (bigint payloads)
 * render as a constant note, matching the gateway's describe() behavior. */
function jsonSchemaOf(schema: z.ZodType): string {
  try {
    return JSON.stringify(z.toJSONSchema(schema))
  } catch {
    return '*(schema not representable as JSON Schema)*'
  }
}

function renderRow(row: MethodRow): { request: string, response: string | undefined } {
  return {
    request: jsonSchemaOf(row.request),
    ...row.response !== undefined ? { response: jsonSchemaOf(row.response) } : {},
  }
}

function renderContract(contract: DomainContract): string {
  const lines: string[] = [`## ${contract.domain}`, '']
  const methods = Object.entries(contract.methods)
  if (methods.length > 0) {
    lines.push('### Methods', '')
    lines.push('| method | request schema | response schema |')
    lines.push('|---|---|---|')
    for (const [name, row] of methods) {
      const rendered = renderRow(row)
      lines.push(`| \`${name}\` | ${rendered.request} | ${rendered.response ?? '—'} |`)
    }
    lines.push('')
  }
  const frames = Object.entries(contract.frames)
  if (frames.length > 0) {
    lines.push('### Frames', '')
    lines.push('| frame | payload schema |')
    lines.push('|---|---|')
    for (const [name, payload] of frames) {
      lines.push(`| \`${name}\` | ${jsonSchemaOf(payload)} |`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

/** The generated document. Exported for the verify gate. */
export function renderCatalog(): string {
  const header = [
    '<!-- Generated by scripts/gen-wire-catalog.ts — do not hand-edit; run `pnpm run gen:wire-catalog`. -->',
    '',
    '# Wire Catalog',
    '',
    'Every client-callable method and host-pushed frame, generated from the',
    'domain contracts (the same single-source declarations the gateway serves;',
    'schemas are the exact zod requests ride with registration). Platform rows',
    '(`host.describe`, `rpc.describe`, `window.*`) are the gateway\'s own',
    'hand-written face and are documented statically here.',
    '',
    '- Methods: `domain.resource.verb`, called as `link.call(name, payload)`.',
    '- Frames: `domain/event`, consumed via `subscribeFrame(link, name, schema, on)`.',
    '',
  ].join('\n')
  return header + '\n' + CONTRACTS.map(renderContract).join('\n') + '\n'
}

const check = process.argv.includes('--check')
const rendered = renderCatalog()
const current = existsSync(catalogPath) ? readFileSync(catalogPath, 'utf8') : undefined
if (check) {
  if (rendered !== current) {
    console.error('verify:wire-catalog — docs/wire-catalog.md drifted from the contracts; run `pnpm run gen:wire-catalog`')
    process.exit(1)
  }
  console.log('verify:wire-catalog — clean')
} else {
  writeFileSync(catalogPath, rendered)
  console.log(`gen:wire-catalog — wrote ${catalogPath}`)
}
