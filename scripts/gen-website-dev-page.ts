/**
 * Generate the website's《插件开发》page content from
 * `docs/plugin-development.md` — the repo doc is the single source of truth;
 * the generated module is committed (same pattern as the feed catalog), and
 * `--check` (wired into `verify:website`) fails the gate on drift.
 *
 *   pnpm run gen:dev-page            # regenerate website/src/generated/dev-page.ts
 *   pnpm run gen:dev-page -- --check # verify the committed output is current
 *
 * The output is deterministic (no timestamps) so `--check` is exact.
 *
 * @module snap-rail/scripts/gen-website-dev-page
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { renderMarkdown } from './lib/markdown.ts'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const docPath = join(repoRoot, 'docs', 'plugin-development.md')
const outFile = join(repoRoot, 'website', 'src', 'generated', 'dev-page.ts')
const check = process.argv.includes('--check')

const { html, toc } = renderMarkdown(readFileSync(docPath, 'utf8'), { skipFirstHeading: true })

const body = `/* Generated by scripts/gen-website-dev-page.ts — do not edit.
 * Source of truth: docs/plugin-development.md. Regenerate with \`pnpm run gen:dev-page\`;
 * \`pnpm run verify:website\` fails when this file drifts from the doc. */

/** One entry of the page's table of contents (h2/h3). */
export interface DevDocTocEntry {
  id: string
  text: string
  level: number
}

/** The rendered doc body (HTML), mounted by website/src/dev.ts. */
export const DEV_DOC_HTML = ${JSON.stringify(html)}

/** The heading tree for the sticky TOC. */
export const DEV_DOC_TOC: DevDocTocEntry[] = ${JSON.stringify(toc, null, 2)}
`

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : ''
  if (current !== body) {
    console.error('gen-website-dev-page — FAIL: dev-page.ts 与 docs/plugin-development.md 不一致')
    console.error('运行 pnpm run gen:dev-page 重新生成并提交。')
    process.exitCode = 1
  } else {
    console.log('gen-website-dev-page — check clean（dev-page.ts 与文档一致）')
  }
} else {
  mkdirSync(dirname(outFile), { recursive: true })
  writeFileSync(outFile, body)
  console.log(`gen-website-dev-page — wrote ${outFile} (${toc.length} headings)`)
}
