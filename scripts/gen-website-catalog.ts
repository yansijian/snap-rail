/**
 * Generate the website's catalog data module from the feed's `catalog.json`
 * (assembled by scripts/publish.ts) plus the desktop release metadata, so
 * the site's plugin catalog and combo cards render exactly what the feed
 * serves — the hand-written copy that used to drift from the feed is gone.
 * Run inside the site build (`pnpm run site:build`); `pnpm run publish`
 * assembles the catalog this reads.
 *
 * The generated module also carries the two URLs every card needs:
 * `FEED_BASE` (download the zips / combo packages / installer) and
 * `REPO_URL` (source home). `SNAP_RAIL_FEED_BASE` and `SNAP_RAIL_REPO_URL`
 * override them for an intranet build; the defaults point at the public
 * GitHub rolling release.
 *
 * @module snap-rail/scripts/gen-website-catalog
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { load } from 'js-yaml'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const catalogFile = join(repoRoot, 'dist-publish', 'plugins', 'catalog.json')
const latestYml = join(repoRoot, 'apps', 'desktop', 'release-out', 'latest.yml')
const outFile = join(repoRoot, 'website', 'src', 'generated', 'catalog.ts')

/** The public feed (the GitHub rolling release), overridable for intranet
 * builds; always ends with `/` so cards can concatenate the file name. */
const FEED_BASE = (process.env.SNAP_RAIL_FEED_BASE ?? 'https://github.com/yansijian/snap-rail/releases/download/feed/').replace(/\/*$/, '/')
const REPO_URL = (process.env.SNAP_RAIL_REPO_URL ?? 'https://github.com/yansijian/snap-rail').replace(/\/*$/, '')

function dirname(path: string): string {
  const index = path.replaceAll('\\', '/').lastIndexOf('/')
  return index < 0 ? '.' : path.slice(0, index)
}

function main(): void {
  if (!existsSync(catalogFile)) {
    throw new Error(`gen-website-catalog: 缺少 ${catalogFile} —— 先运行 pnpm run publish -- --skip-sync（装配 catalog）`)
  }
  const catalog = JSON.parse(readFileSync(catalogFile, 'utf8')) as {
    generatedAt: string
    plugins: unknown[]
    combos: unknown[]
  }
  if (!Array.isArray(catalog.plugins) || !Array.isArray(catalog.combos)) {
    throw new Error('gen-website-catalog: catalog.json 需要 plugins 与 combos 数组')
  }

  // The desktop release trio, when a packaged build exists: latest.yml's
  // version + installer file name become the site's download button.
  let desktop: { version: string, setupFile: string } | null = null
  if (existsSync(latestYml)) {
    const latest = load(readFileSync(latestYml, 'utf8')) as { version?: unknown, path?: unknown }
    if (typeof latest.version === 'string' && typeof latest.path === 'string') {
      desktop = { version: latest.version, setupFile: latest.path }
    }
  }

  const banner = [
    '/* Generated by scripts/gen-website-catalog.ts — do not edit.',
    ' * Source of truth: dist-publish/plugins/catalog.json (the publish pipeline assembles it from the pack output, the collected first-party repos, and the combo sources).',
    ` * Generated at ${new Date().toISOString()} from catalog of ${catalog.generatedAt}. */`,
    '',
  ].join('\n')

  const body = [
    banner,
    '/** One plugin card in the ecosystem catalog (feed facts + repo prose). */',
    'export interface CatalogPlugin {',
    '  name: string',
    '  version: string',
    '  description?: string',
    '  kind?: string',
    '  title?: string',
    '  category?: string',
    '  requires?: string[]',
    '  permissions?: string[]',
    '  file: string',
    '  sha256?: string',
    '  size?: number',
    '  signature?: { algorithm: \'Ed25519\', keyId: string }',
    '  author?: string',
    '  repository?: string',
    '  license?: string',
    '  readme?: string',
    '  screenshots?: string[]',
    '}',
    '',
    '/** One offline combo package card (root recipe.yml + signed member zips). */',
    'export interface CatalogCombo {',
    '  id: string',
    '  version: string',
    '  title: string',
    '  description?: string',
    '  kind: \'base\' | \'scenario\'',
    '  file: string',
    '  plugins: string[]',
    '  readme?: string',
    '  screenshots?: string[]',
    '}',
    '',
    'export interface DesktopRelease {',
    '  version: string',
    '  setupFile: string',
    '}',
    '',
    '/** The rolling release serving plugin zips, combo packages, and the installer. */',
    `export const FEED_BASE = ${JSON.stringify(FEED_BASE)}`,
    '',
    '/** The public source home (GitHub). */',
    `export const REPO_URL = ${JSON.stringify(REPO_URL)}`,
    '',
    '/** The feed catalog the site renders (same release as FEED_BASE). */',
    `export const CATALOG: { generatedAt: string, plugins: CatalogPlugin[], combos: CatalogCombo[], desktop: DesktopRelease | null } = ${JSON.stringify({ generatedAt: catalog.generatedAt, plugins: catalog.plugins, combos: catalog.combos, desktop }, null, 2)}`,
    '',
  ].join('\n')

  mkdirSync(join(repoRoot, 'website', 'src', 'generated'), { recursive: true })
  writeFileSync(outFile, body)
  console.log(`gen-website-catalog — wrote ${outFile} (${catalog.plugins.length} plugins, ${catalog.combos.length} combos, desktop: ${desktop === null ? 'none' : desktop.version})`)
}

main()
