/**
 * Generate the website's catalog data module from the feed's `catalog.json`
 * (assembled by scripts/publish.ts) plus the desktop release metadata, so
 * the site's plugin catalog and recipes pages render exactly what the feed
 * serves — the hand-written copy that used to drift from the feed is gone.
 * Run inside the publish pipeline; `pnpm run publish` does this ahead of the
 * website build. Read from `dist-publish/plugins/catalog.json` — pack first.
 *
 * @module snap-rail/scripts/gen-website-catalog
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { load } from 'js-yaml'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const catalogFile = join(repoRoot, 'dist-publish', 'plugins', 'catalog.json')
const latestYml = join(repoRoot, 'apps', 'desktop', 'release-out', 'latest.yml')
const outFile = join(repoRoot, 'website', 'src', 'generated', 'catalog.ts')

function dirname(path: string): string {
  const index = path.replaceAll('\\', '/').lastIndexOf('/')
  return index < 0 ? '.' : path.slice(0, index)
}

function main(): void {
  if (!existsSync(catalogFile)) {
    throw new Error(`gen-website-catalog: 缺少 ${catalogFile} —— 先运行 pnpm run pack:plugins（或 pnpm run publish）`)
  }
  const catalog = JSON.parse(readFileSync(catalogFile, 'utf8')) as {
    generatedAt: string
    plugins: unknown[]
    recipes: unknown[]
  }

  // The desktop release trio, when a packaged build exists: latest.yml's
  // version + installer file name become the site's download button.
  let desktop: { version: string, setupFile: string } | null = null
  if (existsSync(latestYml)) {
    const latest = load(readFileSync(latestYml, 'utf8')) as { version?: unknown, path?: unknown }
    if (typeof latest.version === 'string' && typeof latest.path === 'string') {
      desktop = { version: latest.version, setupFile: latest.path }
    }
  }

  const banner = [
    '/* Generated by scripts/gen-website-catalog.ts — do not edit.',
    ' * Source of truth: dist-publish/plugins/catalog.json (the publish pipeline assembles it from the pack output and the repo sources).',
    ` * Generated at ${new Date().toISOString()} from catalog of ${catalog.generatedAt}. */`,
    '',
  ].join('\n')

  const body = [
    banner,
    '/** One plugin card in the ecosystem catalog (feed facts + repo prose). */',
    'export interface CatalogPlugin {',
    '  name: string',
    '  version: string',
    '  description?: string',
    '  kind?: string',
    '  title?: string',
    '  category?: string',
    '  requires?: string[]',
    '  framework?: string',
    '  permissions?: string[]',
    '  file: string',
    '  sha256?: string',
    '  size?: number',
    '  author?: string',
    '  repository?: string',
    '  license?: string',
    '  readme?: string',
    '  screenshots?: string[]',
    '}',
    '',
    '/** One combination (recipe) card on the recipes page. */',
    'export interface CatalogRecipe {',
    '  id: string',
    '  version: string',
    '  title: string',
    "  description?: string",
    "  kind: 'base' | 'scenario'",
    '  file: string',
    '  plugins: string[]',
    '  readme?: string',
    '  screenshots?: string[]',
    '}',
    '',
    'export interface DesktopRelease {',
    '  version: string',
    '  setupFile: string',
    '}',
    '',
    '/** The feed catalog the site renders (same-origin with the feed). */',
    `export const CATALOG: { generatedAt: string, plugins: CatalogPlugin[], recipes: CatalogRecipe[], desktop: DesktopRelease | null } = ${JSON.stringify({ generatedAt: catalog.generatedAt, plugins: catalog.plugins, recipes: catalog.recipes, desktop }, null, 2)}`,
    '',
  ].join('\n')

  mkdirSync(join(repoRoot, 'website', 'src', 'generated'), { recursive: true })
  writeFileSync(outFile, body)
  console.log(`gen-website-catalog — wrote ${outFile} (${catalog.plugins.length} plugins, ${catalog.recipes.length} recipes, desktop: ${desktop === null ? 'none' : desktop.version})`)
}

main()
